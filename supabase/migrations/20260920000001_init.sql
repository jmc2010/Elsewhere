-- Household-scoped access. SECURITY DEFINER avoids recursive RLS evaluation
-- when household_members is itself the table being filtered.
create function is_household_member(h uuid)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from household_members
    where household_id = h and user_id = auth.uid()
  );
$$;

create policy households_member on households
  for select to authenticated using (is_household_member(id));

create policy household_members_member on household_members
  for select to authenticated using (is_household_member(household_id));

create policy visits_member on visits
  for all to authenticated
  using (is_household_member(household_id))
  with check (is_household_member(household_id));

create policy meals_member on meals
  for all to authenticated
  using (is_household_member(household_id))
  with check (is_household_member(household_id));

create policy meal_candidates_member on meal_candidates
  for all to authenticated
  using (exists (select 1 from meals m
                 where m.id = meal_id and is_household_member(m.household_id)))
  with check (exists (select 1 from meals m
                      where m.id = meal_id and is_household_member(m.household_id)));

create policy meal_votes_member on meal_votes
  for all to authenticated
  using (exists (select 1 from meals m
                 where m.id = meal_id and is_household_member(m.household_id)))
  with check (user_id = auth.uid());

create policy visit_attendees_member on visit_attendees
  for all to authenticated
  using (exists (select 1 from visits v
                 where v.id = visit_id and is_household_member(v.household_id)))
  with check (exists (select 1 from visits v
                      where v.id = visit_id and is_household_member(v.household_id)));
